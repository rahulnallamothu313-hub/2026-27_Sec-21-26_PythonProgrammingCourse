# python comparision operator exercise
A=20
B=60
result = A > B #Greater than comparision
print("result of",A, ">",B,"is :",result)
result = A < B #Less than comparision
print("result of",A, "<",B,"is :",result)
result = A != B #Not equal to comparision
print("result of",A, "!=",B, "is :",result)
result = A == B # Equal to comparision
print("result of ",A, "==",B, "is :",result)
result = A >= B #Greater than or equal to comparision
print("result of ",A, ">=",B, "is :",result)
result = A <= B # less than or equal to comparision
print("result of ",A, "<=",B, "is :",result)

